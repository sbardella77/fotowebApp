function serialize(value, indent = 2) {
  const prefix = ' '.repeat(indent);
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return String(value);
  if (value === null) return 'null';
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return '[\n' + value.map(v => prefix + '  ' + serialize(v, indent + 2) + ',').join('\n') + '\n' + prefix + ']';
  }
  const keys = Object.keys(value);
  if (keys.length === 0) return '{}';
  return '{\n' + keys.map(k => prefix + '  ' + JSON.stringify(k) + ': ' + serialize(value[k], indent + 2) + ',').join('\n') + '\n' + prefix + '}';
}

const out = 'export const dictionaries = ' + serialize(dictionaries) + ';\n\nexport function getDictionary(locale) {\n  return dictionaries[locale] || dictionaries.en;\n}\n';

